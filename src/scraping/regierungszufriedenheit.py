"""
Generated by Claude

ARD-DeutschlandTrend: satisfaction with the German federal government
======================================================================

What this script does
---------------------
1. Download
   Crawls https://www.tagesschau.de/inland/deutschlandtrend (current year(s))
   and every yearly archive page (.../deutschlandtrend/archiv/<year>, from
   2013 on). The PDF links ("Alle Grafiken zum Download") are collected from
   those listing pages and from every DeutschlandTrend article linked there.
   All PDFs published from the February 2013 edition onwards are saved to
   ../../data/raw/deutschlandtrend (relative to this file). Files that already
   exist are not downloaded again.

2. Extraction
   Every PDF in that folder is searched for the question
   "Wie zufrieden sind Sie mit der Arbeit der Bundesregierung?". The values
   for "sehr zufrieden", "zufrieden", "weniger zufrieden" and
   "gar nicht zufrieden" are written to ../../data/interim/regierungszufriedenheit.csv
   with the schema:

       Datum | sehr zufrieden | zufrieden | weniger zufrieden | gar nicht zufrieden

   "Datum" is the last day of the survey period ("Erhebungszeitraum").
   PDFs without the question (e.g. state polls, special editions) are skipped,
   as are PDFs that only report aggregated values (e.g. April 2018).

Important notes
---------------
* The PDF layout changed several times since 2013 (portrait/landscape,
  rotated pages, one or two slides per page, an additional chart with party
  supporters on the same slide, ...). The values are therefore located by
  their position: the number standing directly above each category label is
  taken as the value of that category.
* Some PDFs from 2013 - 2015 contain the chart only as a raster image, i.e.
  the numbers are not available as text. The changes to the previous edition
  ("(+4)", "Angaben in Klammern: Vergleich zu ...") are still text, so these
  values are reconstructed as "values of the reference edition + changes".
  Without a reference edition the bar heights are measured on the rendered
  page and scaled to 100 % minus "weiß nicht" (only used for May 2013). The
  bar heights also serve as a cross-check for the reconstructed values.
* The February 2013 edition was published on 31 January 2013, so the
  download cutoff is based on the publication date of that edition.
* Values of the same survey (same end date) found in several PDFs are only
  stored once.

Usage
-----
    pip install -r requirements.txt
    python src/scraping/regierungszufriedenheit.py              # download + extract
    python src/scraping/regierungszufriedenheit.py --no-download  # extract only

Dependencies: requests, beautifulsoup4, pymupdf
"""

