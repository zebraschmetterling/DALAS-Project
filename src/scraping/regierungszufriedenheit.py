def fetch(url: str) -> requests.Response | None:
    """GET a URL with retries. Returns None for 404 or if all retries fail."""
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = session.get(url, timeout=REQUEST_TIMEOUT)
            time.sleep(REQUEST_DELAY)
            if response.status_code == 404:
                return None
            response.raise_for_status()
            return response
        except requests.RequestException as exc:
            print(f"  Request failed ({attempt}/{MAX_RETRIES}) for {url}: {exc}")
            time.sleep(2 ** attempt)
    return None


def fetch_soup(url: str) -> BeautifulSoup | None:
    response = fetch(url)
    return BeautifulSoup(response.text, "html.parser") if response else None


def parse_german_date(text: str) -> date | None:
    """Find the first date in the format dd.mm.yyyy in a text."""
    match = re.search(r"(\d{2})\.(\d{2})\.(\d{4})", text)
    if not match:
        return None
    day, month, year = map(int, match.groups())
    return date(year, month, day)


def article_publication_date(soup: BeautifulSoup) -> date | None:
    """Publication date of an article page (meta tag, fallback: first date in the text)."""
    meta = soup.find("meta", attrs={"name": "date"})
    if meta and meta.get("content"):
        try:
            return datetime.fromisoformat(meta["content"][:19]).date()
        except ValueError:
            pass
    return parse_german_date(soup.get_text(" "))


def is_pdf_link(url: str) -> bool:
    return urlparse(url).path.lower().endswith(".pdf")


def is_article_link(url: str) -> bool:
    """DeutschlandTrend article pages on tagesschau.de (archive pages excluded)."""
    parsed = urlparse(url)
    return (
        parsed.netloc.endswith("tagesschau.de")
        and "deutschlandtrend" in parsed.path
        and parsed.path.endswith(".html")
        and "/archiv" not in parsed.path
    )


def listing_pages() -> list[str]:
    """Overview page plus all yearly archive pages from FIRST_YEAR on.

    The available archive years are read from the links on the overview page,
    so new archive years are picked up automatically. Only if no such link is
    found, every year up to last year is tried.
    """
    years: set[int] = set()
    soup = fetch_soup(OVERVIEW_URL)
    if soup:
        for link in soup.find_all("a", href=True):
            match = re.search(r"/deutschlandtrend/archiv/(\d{4})", link["href"])
            if match:
                years.add(int(match.group(1)))
    if not years:
        years = set(range(FIRST_YEAR, date.today().year))
    return [OVERVIEW_URL] + [ARCHIVE_URL.format(year=y) for y in sorted(years) if y >= FIRST_YEAR]


def collect_pdf_links() -> dict[str, date]:
    """Return {pdf_url: publication date} for all DeutschlandTrend PDFs found.

    A PDF can be linked from several pages; the earliest publication date wins.
    """
    pdf_dates: dict[str, date] = {}
    article_urls: set[str] = set()

    def remember(pdf_url: str, published: date | None) -> None:
        if published is None:
            return
        if pdf_url not in pdf_dates or published < pdf_dates[pdf_url]:
            pdf_dates[pdf_url] = published

    # Step 1: listing pages (overview + archive). Some archive years link the
    # PDFs directly below a teaser, the date is taken from that teaser.
    for page_url in listing_pages():
        soup = fetch_soup(page_url)
        if soup is None:
            print(f"Listing page not available, skipped: {page_url}")
            continue
        print(f"Scanning listing page: {page_url}")
        for link in soup.find_all("a", href=True):
            url = urljoin(BASE_URL, link["href"]).split("#")[0]
            if is_pdf_link(url):
                teaser_date = link.find_previous(class_="teaser__date")
                remember(url, parse_german_date(teaser_date.get_text()) if teaser_date else None)
            elif is_article_link(url):
                article_urls.add(url)

    # Step 2: article pages, most PDFs are only linked there.
    print(f"Scanning {len(article_urls)} article pages for PDF links ...")
    for index, article_url in enumerate(sorted(article_urls), start=1):
        soup = fetch_soup(article_url)
        if soup is None:
            continue
        published = article_publication_date(soup)
        for link in soup.find_all("a", href=True):
            url = urljoin(BASE_URL, link["href"]).split("#")[0]
            if is_pdf_link(url):
                remember(url, published)
        if index % 50 == 0:
            print(f"  {index}/{len(article_urls)} article pages scanned")

    return pdf_dates


def download_pdfs(pdf_dates: dict[str, date], target_dir: Path) -> None:
    """Download all PDFs published on/after MIN_PUBLICATION_DATE that are not on disk yet."""
    target_dir.mkdir(parents=True, exist_ok=True)
    wanted = {url: d for url, d in pdf_dates.items() if d >= MIN_PUBLICATION_DATE}
    print(f"{len(wanted)} PDFs published since {MIN_PUBLICATION_DATE:%d.%m.%Y} found.")

    downloaded = skipped = failed = 0
    for url, published in sorted(wanted.items(), key=lambda item: item[1]):
        target = target_dir / Path(urlparse(url).path).name
        if target.exists() and target.stat().st_size > 0:
            skipped += 1
            continue
        response = fetch(url)
        if response is None or not response.content.startswith(b"%PDF"):
            print(f"  Download failed: {url}")
            failed += 1
            continue
        # Write to a temporary file first so an interrupted download never
        # leaves a broken PDF that would be skipped on the next run.
        tmp = target.with_suffix(".part")
        tmp.write_bytes(response.content)
        tmp.replace(target)
        downloaded += 1
        print(f"  Downloaded {target.name} (published {published:%d.%m.%Y})")

    print(f"Download finished: {downloaded} new, {skipped} already present, {failed} failed.")


