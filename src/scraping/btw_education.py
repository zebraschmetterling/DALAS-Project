def find_btw_pdf_links(min_year: int) -> dict[int, str]:
    """Return {election_year: pdf_url} for all Bundestag elections >= min_year.

    The overview page contains one table row per election: the first cell holds
    the election name (e.g. "Bundestagswahl 2021"), the second cell the link
    labelled "Kurzanalyse".
    """
    response = requests.get(BASE_URL, headers=HTTP_HEADERS, timeout=HTTP_TIMEOUT)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, "html.parser")

    links: dict[int, str] = {}
    for row in soup.find_all("tr"):
        cells = row.find_all("td")
        if len(cells) < 2:
            continue

        name = " ".join(cells[0].get_text(" ", strip=True).split())
        match = re.fullmatch(r"Bundestagswahl\s+(\d{4})", name)
        if not match:
            continue
        year = int(match.group(1))
        if year < min_year:
            continue

        # Prefer the link explicitly called "Kurzanalyse", otherwise take the first PDF link.
        pdf_links = [a for a in row.find_all("a", href=True) if ".pdf" in a["href"].lower()]
        kurzanalyse = [a for a in pdf_links if "kurzanalyse" in a.get_text(strip=True).lower()]
        chosen = (kurzanalyse or pdf_links or [None])[0]
        if chosen is None:
            print(f"  [warn] No PDF link found for Bundestagswahl {year}")
            continue

        # Strip session ids such as ";jsessionid=..." that are sometimes appended.
        href = chosen["href"].split(";")[0]
        links[year] = urljoin(BASE_URL, href)

    return dict(sorted(links.items(), reverse=True))


def download_pdf(url: str, target: Path) -> None:
    """Download a PDF to `target` (via a temporary file, so aborted downloads leave no broken PDF)."""
    response = requests.get(url, headers=HTTP_HEADERS, timeout=HTTP_TIMEOUT)
    response.raise_for_status()
    if not response.content.startswith(b"%PDF"):
        raise ValueError(f"Response from {url} is not a PDF")

    tmp_path = target.with_suffix(target.suffix + ".part")
    tmp_path.write_bytes(response.content)
    tmp_path.replace(target)


def download_kurzanalysen(min_year: int) -> None:
    """Download all missing Kurzanalyse PDFs of Bundestag elections >= min_year."""
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    print(f"Fetching election overview: {BASE_URL}")

    try:
        links = find_btw_pdf_links(min_year)
    except requests.RequestException as exc:
        # Without the website we can still parse PDFs that were downloaded earlier.
        print(f"  [warn] Could not load overview page ({exc}); using existing files only.")
        return

    if not links:
        print("  [warn] No Bundestag election PDFs found on the overview page.")
        return

    for year, url in links.items():
        target = RAW_DIR / PDF_NAME_TEMPLATE.format(year=year)
        if target.exists():
            print(f"  [skip] {year}: {target.name} already exists")
            continue
        try:
            download_pdf(url, target)
            print(f"  [done] {year}: downloaded {url} -> {target.name}")
        except (requests.RequestException, ValueError) as exc:
            print(f"  [error] {year}: download of {url} failed ({exc})")


