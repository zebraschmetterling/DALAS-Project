PDF_NAME_REGEX = re.compile(r"^Bundestagswahl_(\d{4})_Kurzanalyse\.pdf$")

CHART_TITLE_REGEX = r"Wahlentscheidung\s+in\s+den\s+Bildungsgruppen"

