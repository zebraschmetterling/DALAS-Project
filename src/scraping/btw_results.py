#!/usr/bin/env python3
"""
Generated by Claude

Bundestag elections: download and process results by federal state and for
the whole federal territory.

Summary:
- Data source: btw_kerg.zip ("Endgültige Ergebnisse nach Wahlkreisen aller
  Bundestagswahlen" / "Final results by constituency for all federal
  elections") from the Federal Returning Officer (bundeswahlleiterin.de).
- Step 1: Download the ZIP (skipped if it already exists, unless --force) and
  extract it to ../../data/raw/btw_kerg.
- Step 2: For all elections from MIN_YEAR onwards, read the kerg file (not
  kerg2) and keep only the aggregate rows: the 16 federal states
  ("gehört zu" = 99) and the federal territory ("Bundesgebiet", empty
  "gehört zu"). Constituency rows are skipped.
- Output: ../../data/interim/btw_results.csv with 17 rows per election
  (16 states sorted by official state number, then "Bundesgebiet").
- Schema: identical to btw_wahlkreise.csv, except that the column "Wahlkreis"
  is replaced by "Gebiet" (state name or "Bundesgebiet") and
  "Direkt gewählter Abgeordnete" is dropped, because direct
  mandates only exist at constituency level.
- Votes are grouped into the parties CDU/CSU, SPD, Grüne, FDP, Linke, AfD,
  FW, BSW; everything else goes into "Sonstige" (valid votes minus the named
  groups). Only the final ("Endgültig") values are used, never "Vorperiode".
- A party group that did not stand in an area (e.g. CDU in Bayern, BSW
  before 2025) is left empty instead of 0, separately for first and second
  votes. "Sonstige" always has a value.
- Sanity checks: number of rows per election, and whether the sum over the
  states matches the federal territory row.

Paths are relative to the location of this script.

Requires:  pip install requests
Usage:     python btw_results.py [--force] [--min-year 2013]
"""
from __future__ import annotations

import argparse
import csv
import io
import re
import sys
import zipfile
from pathlib import Path
from urllib.parse import urljoin

import requests

# --------------------------------------------------------------------------- #
# Configuration
# --------------------------------------------------------------------------- #
BASE_DIR = Path(__file__).resolve().parent
RAW_DIR = (BASE_DIR / "../../data/raw").resolve()
INTERIM_DIR = (BASE_DIR / "../../data/interim").resolve()

PAGE_URL = "https://www.bundeswahlleiterin.de/bundestagswahlen/2025/ergebnisse.html"
# Fallback in case the link on the page cannot be found
FALLBACK_ZIP_URL = (
    "https://www.bundeswahlleiterin.de/dam/jcr/"
    "ce2d2b6a-f211-4355-8eea-355c98cd4e47/btw_kerg.zip"
)
ZIP_NAME = "btw_kerg.zip"
EXTRACT_DIR = RAW_DIR / "btw_kerg"
OUTPUT_NAME = "btw_results.csv"

MIN_YEAR = 2013  # inclusive ("from 2013"); can be changed via --min-year
EXPECTED_STATES = 16
FEDERAL_NAME = "Bundesgebiet"

# Value of the "gehört zu" (belongs to) column that marks a federal state row
STATE_PARENT = "99"

HTTP_HEADERS = {"User-Agent": "Mozilla/5.0 (compatible; btw-kerg-pipeline/1.0)"}

# Party groups in the order of the output table ("Sonstige"/"Other" comes last)
GROUPS = ["CDU/CSU", "SPD", "Grüne", "FDP", "Linke", "AfD", "FW", "BSW"]
OTHER = "Sonstige"

# Same schema as btw_wahlkreise.csv, with "Gebiet" instead of "Wahlkreis"
FIELDNAMES = (
    ["Jahr", "Gebiet", "Wahlberechtigte", "Wählende" ]
    + [f"Erststimmen {g}" for g in GROUPS + [OTHER]]
    + [f"Zweitstimmen {g}" for g in GROUPS + [OTHER]]
)

# Columns that are summed over the states and compared with the federal row
CHECK_COLUMNS = [c for c in FIELDNAMES if c not in ("Jahr", "Gebiet", "Direkt gewählter Abgeordnete")]

DASHES = {"", "-", "–", "—", "‑"}
KIND_MAP = {"erststimmen": "erst", "zweitstimmen": "zweit"}


# --------------------------------------------------------------------------- #
# Helper functions
# --------------------------------------------------------------------------- #
def norm(text: str) -> str:
    """Normalize whitespace, casefold, remove trailing period."""
    text = text.replace("\xa0", " ")
    return re.sub(r"\s+", " ", text).strip().casefold().rstrip(".")


def classify(name: str) -> str | None:
    """Party name (long form or abbreviation, depending on election year) -> party group."""
    n = norm(name)
    if n in {"cdu", "csu"} or n.startswith(
        ("christlich demokratische union", "christlich-soziale union")
    ):
        return "CDU/CSU"
    if n == "spd" or n.startswith("sozialdemokratische partei"):
        return "SPD"
    if n in {"grüne", "gruene"} or n.startswith("bündnis 90"):
        return "Grüne"
    if n == "fdp" or n.startswith("freie demokratische partei"):
        return "FDP"
    if n in {"die linke", "linke"}:
        return "Linke"
    if n == "afd" or n.startswith("alternative für deutschland"):
        return "AfD"
    if n in {"freie wähler", "fw"}:
        return "FW"
    if n == "bsw" or n.startswith("bündnis sahra wagenknecht"):
        return "BSW"
    return None


def block_role(name: str) -> str:
    """Is the column group a metric or a party?"""
    n = norm(name)
    if n.startswith("wahlberechtigte"):
        return "wahlberechtigte"
    if n in {"wähler", "wählende", "waehler", "waehlende"}:
        return "waehlende"
    if n.startswith("ungültige"):
        return "ungueltige"
    if n.startswith("gültige"):
        return "gueltige"
    if n in {"übrige", "sonstige"}:
        return "uebrige"
    return "party"


def to_int(value: str) -> int:
    """Parse a number from the CSV; dashes and empty cells count as 0."""
    value = value.strip().replace(".", "").replace(" ", "")
    if value in DASHES:
        return 0
    try:
        return int(value)
    except ValueError:
        return int(float(value.replace(",", ".")))


def cell(row: list[str], idx: int | None) -> int:
    """Integer value of a cell; missing columns count as 0."""
    if idx is None or idx >= len(row):
        return 0
    return to_int(row[idx])


def cell_or_none(row: list[str], idx: int | None) -> int | None:
    """Integer value of a party cell, or None if the party did not stand.

    In the final ("Endgültig") columns the source leaves the cell empty when a
    party did not stand in an area; a real zero is written as "0".
    """
    if idx is None or idx >= len(row) or row[idx].strip() in DASHES:
        return None
    return to_int(row[idx])


def area_sort_key(nr: int) -> int:
    """
    Sort key for an aggregate row: states by official state number (1-16),
    federal territory last (99). The 2013 file numbers its aggregate rows
    901-916 and 999 instead of 1-16 and 99, so the offset is removed.
    """
    return nr - 900 if nr > 900 else nr


# --------------------------------------------------------------------------- #
# Step 1: Download + extract
# --------------------------------------------------------------------------- #
def find_zip_url(session: requests.Session) -> str:
    """Read the btw_kerg.zip link from the results page (the hash in the path may change)."""
    try:
        resp = session.get(PAGE_URL, timeout=30)
        resp.raise_for_status()
        match = re.search(r'href="([^"]*btw_kerg\.zip)"', resp.text)
        if match:
            return urljoin(PAGE_URL, match.group(1))
        print("Note: link not found on the page, using fallback URL.")
    except requests.RequestException as exc:
        print(f"Note: page could not be read ({exc}), using fallback URL.")
    return FALLBACK_ZIP_URL


def download_zip(force: bool) -> Path:
    """Download btw_kerg.zip to RAW_DIR unless it already exists (or --force is set)."""
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    zip_path = RAW_DIR / ZIP_NAME
    if zip_path.exists() and not force:
        print(f"ZIP already exists, skipping download: {zip_path}")
        return zip_path

    with requests.Session() as session:
        session.headers.update(HTTP_HEADERS)
        url = find_zip_url(session)
        print(f"Downloading {url}")
        # Write to a temporary file first so an aborted download never
        # leaves a broken ZIP behind under the final name
        tmp_path = zip_path.with_suffix(".zip.part")
        with session.get(url, stream=True, timeout=120) as resp:
            resp.raise_for_status()
            with open(tmp_path, "wb") as fh:
                for chunk in resp.iter_content(chunk_size=1 << 16):
                    fh.write(chunk)

    if not zipfile.is_zipfile(tmp_path):
        tmp_path.unlink(missing_ok=True)
        raise RuntimeError("The downloaded file is not a valid ZIP file.")
    tmp_path.replace(zip_path)
    print(f"Saved: {zip_path}")
    return zip_path


def extract_zip(zip_path: Path) -> Path:
    """Extract the ZIP into EXTRACT_DIR (existing files are overwritten)."""
    EXTRACT_DIR.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path) as zf:
        zf.extractall(EXTRACT_DIR)
    print(f"Extracted to: {EXTRACT_DIR}")
    return EXTRACT_DIR


# --------------------------------------------------------------------------- #
# Step 2: Read kerg files
# --------------------------------------------------------------------------- #
def find_kerg_files(root: Path) -> list[Path]:
    """All *kerg*.csv, but not *kerg2*.csv."""
    files = []
    for path in sorted(root.rglob("*.csv")):
        name = path.name.casefold()
        # Ignore macOS metadata files that are sometimes included in ZIPs
        if "__macosx" in str(path).casefold() or name.startswith("._"):
            continue
        if "kerg" in name and "kerg2" not in name:
            files.append(path)
    return files


def read_rows(path: Path) -> list[list[str]]:
    """Read a semicolon-separated CSV; the encoding differs between election years."""
    raw = path.read_bytes()
    for enc in ("utf-8-sig", "cp1252", "latin-1"):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    return list(csv.reader(io.StringIO(text), delimiter=";"))


def detect_year(rows: list[list[str]], path: Path) -> int | None:
    """Election year from the file header, otherwise from the file name."""
    for row in rows[:10]:
        m = re.search(r"Bundestagswahl\s+(\d{4})", " ".join(row))
        if m:
            return int(m.group(1))
    m = re.search(r"(?<!\d)((?:19|20)\d{2})(?!\d)", path.name)
    if m:
        return int(m.group(1))
    m = re.search(r"btw(\d{2})", path.name, re.IGNORECASE)
    if m:
        yy = int(m.group(1))
        return 2000 + yy if yy < 50 else 1900 + yy
    return None


def find_header_row(rows: list[list[str]]) -> int:
    """Index of the header row with the column group names (first cell 'Nr')."""
    for i, row in enumerate(rows):
        if row and norm(row[0]) == "nr":
            return i
    raise ValueError("Header row (starting with 'Nr') not found")


def parse_kerg_file(path: Path) -> tuple[int | None, list[dict]]:
    """
    Read a kerg file (wide format) and return the state and federal rows.

    Structure: a header row with group names (4 columns each), followed by
    an "Erststimmen/Zweitstimmen" (first/second votes) row and an
    "Endgültig/Vorperiode" (final/previous period) row. Each group therefore
    has 4 columns: first final, first previous, second final, second
    previous. Only the final values are used.

    Returns: (year, rows)
    """
    rows = read_rows(path)
    year = detect_year(rows, path)
    h = find_header_row(rows)

    names, kinds = rows[h], rows[h + 1]
    period_row_ok = h + 2 < len(rows) and any(
        norm(c).startswith("endg") for c in rows[h + 2]
    )
    periods = rows[h + 2] if period_row_ok else []
    data_start = h + 3 if period_row_ok else h + 2

    # --- Map columns ------------------------------------------------------- #
    # blocks: group name -> {"erst": column index, "zweit": column index}
    blocks: dict[str, dict[str, int]] = {}
    block: str | None = None
    kind: str | None = None
    width = max(len(names), len(kinds), len(periods))
    for j in range(width):
        name = names[j].strip() if j < len(names) else ""
        k = norm(kinds[j]) if j < len(kinds) else ""
        # Group names and vote kinds are only written in the first column
        # they apply to, so the last seen value is carried forward
        if k:
            kind = k
        if name:
            n = norm(name)
            # The "Gewählt" (elected) column is irrelevant for states and
            # the federal territory, but must not be mistaken for a party
            if n == "gewählt" or n.startswith("direkt"):
                block = None
                continue
            block = name
        if block is None or kind not in KIND_MAP:
            continue
        if period_row_ok:
            p = norm(periods[j]) if j < len(periods) else ""
            if not p.startswith("endg"):
                continue
        blocks.setdefault(block, {}).setdefault(KIND_MAP[kind], j)

    # Split the column groups into metrics (eligible voters, voters, ...) and parties
    meta: dict[str, dict[str, int]] = {}
    parties: dict[str, dict[str, int]] = {}
    for bname, idx in blocks.items():
        role = block_role(bname)
        if role == "party":
            parties[bname] = idx
        else:
            meta[role] = idx
    for needed in ("wahlberechtigte", "waehlende"):
        if needed not in meta:
            raise ValueError(f"Column '{needed}' not found")

    # --- Data rows --------------------------------------------------------- #
    out: list[dict] = []
    for row in rows[data_start:]:
        if len(row) < 4 or not row[0].strip().isdigit():
            continue
        nr, gebiet, parent = row[0].strip(), row[1].strip(), row[2].strip()
        # Keep only states ("gehört zu" = 99) and the federal territory
        # (empty "gehört zu"); constituencies belong to a state number
        if parent not in ("", STATE_PARENT):
            continue

        # Sum the first and second votes per party group. A group only gets a
        # value if at least one of its parties stood in this area for this
        # vote; otherwise it stays None and is written as an empty cell
        erst: dict[str, int | None] = {g: None for g in GROUPS}
        zweit: dict[str, int | None] = {g: None for g in GROUPS}
        for pname, idx in parties.items():
            g = classify(pname)
            if not g:
                continue
            for sums, stimme in ((erst, "erst"), (zweit, "zweit")):
                v = cell_or_none(row, idx.get(stimme))
                if v is not None:
                    sums[g] = (sums[g] or 0) + v

        def remainder(stimme: str, sums: dict[str, int | None]) -> int:
            """'Other' votes: valid votes minus the named groups, or the sum of
            all unclassified parties if no valid-votes column is available."""
            named = sum(sums[g] or 0 for g in GROUPS)
            valid = cell(row, meta.get("gueltige", {}).get(stimme))
            if valid:
                return valid - named
            rest = sum(
                cell(row, idx.get(stimme))
                for pname, idx in parties.items()
                if not classify(pname)
            )
            return rest + cell(row, meta.get("uebrige", {}).get(stimme))

        erst[OTHER] = remainder("erst", erst)
        zweit[OTHER] = remainder("zweit", zweit)
        if erst[OTHER] < 0 or zweit[OTHER] < 0:
            print(f"  Warning {year} {gebiet}: negative 'other' votes")

        # Some files only fill in one of the two vote kinds for these metrics
        wahlberechtigte = cell(row, meta["wahlberechtigte"].get("erst")) or cell(
            row, meta["wahlberechtigte"].get("zweit")
        )
        waehlende = cell(row, meta["waehlende"].get("erst")) or cell(
            row, meta["waehlende"].get("zweit")
        )

        rec = {
            "Jahr": year,
            "Gebiet": gebiet,
            "Wahlberechtigte": wahlberechtigte,
            "Wählende": waehlende,
            # Direct mandates only exist per constituency, so this stays empty
            "Direkt gewählter Abgeordnete": "",
            "_sort": area_sort_key(int(nr)),
            "_is_federal": parent == "",
        }
        for g in GROUPS + [OTHER]:
            rec[f"Erststimmen {g}"] = erst[g]
            rec[f"Zweitstimmen {g}"] = zweit[g]
        out.append(rec)

    return year, out


def check_year(year: int, rows: list[dict]) -> None:
    """Warn if states or the federal row are missing, or if the state totals
    do not add up to the federal territory."""
    states = [r for r in rows if not r["_is_federal"]]
    federal = [r for r in rows if r["_is_federal"]]
    if len(states) != EXPECTED_STATES:
        print(f"  Warning: expected {EXPECTED_STATES} states, found {len(states)}")
    if len(federal) != 1:
        print(f"  Warning: expected 1 federal territory row, found {len(federal)}")
        return
    if federal[0]["Gebiet"] != FEDERAL_NAME:
        print(f"  Note {year}: federal row is named '{federal[0]['Gebiet']}'")

    # Empty cells (party did not stand) count as 0 in the comparison
    mismatches = [
        col
        for col in CHECK_COLUMNS
        if sum(r[col] or 0 for r in states) != (federal[0][col] or 0)
    ]
    if mismatches:
        print(f"  Warning {year}: sum of states differs from federal total in {mismatches}")


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--force", action="store_true", help="download the ZIP even if it already exists")
    ap.add_argument("--min-year", type=int, default=MIN_YEAR, help="first election year to include")
    args = ap.parse_args()

    # 1) Download + extract
    zip_path = download_zip(args.force)
    root = extract_zip(zip_path)

    # 2) Process kerg files
    files = find_kerg_files(root)
    if not files:
        print("No kerg files found in the ZIP.", file=sys.stderr)
        return 1
    print(f"Found kerg files: {[f.name for f in files]}")

    # Pick one file per election year (the first one in sorted order wins)
    by_year: dict[int, Path] = {}
    for f in files:
        try:
            year = detect_year(read_rows(f), f)
        except Exception as exc:  # noqa: BLE001
            print(f"Skipping {f.name}: {exc}")
            continue
        if year is None:
            print(f"Skipping {f.name}: election year not recognized")
        elif year < args.min_year:
            continue
        elif year in by_year:
            print(f"Warning: multiple files for {year}, using {by_year[year].name}")
        else:
            by_year[year] = f

    all_rows: list[dict] = []
    for year in sorted(by_year):
        path = by_year[year]
        print(f"Processing {year}: {path.name}")
        _, rows = parse_kerg_file(path)
        n_states = sum(not r["_is_federal"] for r in rows)
        print(f"  {n_states} states, {len(rows) - n_states} federal territory row(s)")
        check_year(year, rows)
        all_rows.extend(rows)

    if not all_rows:
        print("No data extracted.", file=sys.stderr)
        return 1

    # States in official order, federal territory last within each year
    all_rows.sort(key=lambda r: (r["Jahr"], r["_sort"]))

    INTERIM_DIR.mkdir(parents=True, exist_ok=True)
    out_path = INTERIM_DIR / OUTPUT_NAME
    with open(out_path, "w", newline="", encoding="utf-8") as fh:
        # extrasaction="ignore" drops the internal helper keys (_sort, _is_federal)
        writer = csv.DictWriter(fh, fieldnames=FIELDNAMES, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(all_rows)
    print(f"Done: {len(all_rows)} rows -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
