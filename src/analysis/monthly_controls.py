"""
Generated by Claude

Interactive plot of the monthly control variables over time.

MOST IMPORTANT: A line is only drawn where data is (almost) continuous. If a
variable is missing for two or more months in a row, the line breaks there;
a single missing month is bridged. Every data point is marked with a dot, so
isolated values between two gaps stay visible.

Input:  ../../data/processed/monthly_controls.csv
Output: ../../dashboard/monthly_controls.html (open in any browser, works offline)

Interaction: hover shows all three values for a month, drag to zoom, double-click
to reset, and the buttons / range slider select the time window.

Run with:
    python src/Analysis/monthly_controls.py
"""

from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
from plotly.subplots import make_subplots

# Resolve paths relative to this script, so it works from any working directory.
SCRIPT_DIR = Path(__file__).resolve().parent
INPUT_PATH = SCRIPT_DIR / "../../data/processed/monthly_controls.csv"
OUTPUT_PATH = SCRIPT_DIR / "../../dashboard/monthly_controls.html"

# The line breaks once this many consecutive months are missing.
MIN_GAP_MONTHS = 2

# Column, axis label, line colour, marker size, hover format.
PANELS = [
    ("Gouvernement Satisfaction", "Satisfied (%)", "#1f77b4", 6, "%{y}%"),
    ("Unemployment rate", "Unemployment (%)", "#d62728", 3, "%{y:.1f}%"),
    ("Asylum applications", "Applications", "#2ca02c", 3, "%{y:,}"),
]


def with_gaps(df: pd.DataFrame, col: str) -> tuple[pd.Series, int]:
    """Return the monthly series of one variable, prepared for plotting.

    Plotly breaks a line at every missing value. So single missing months are
    removed (the line bridges them), while gaps of MIN_GAP_MONTHS or more stay
    in the series as missing values (the line breaks). Also returns the number
    of such gaps.
    """
    series = df.set_index("Date")[col]
    # Fill in every calendar month, so months absent from the CSV count as missing.
    months = pd.date_range(series.index.min(), series.index.max(), freq="MS")
    series = series.reindex(months)

    # Label each run of consecutive missing / present months and measure its length.
    missing = series.isna()
    run_id = (missing != missing.shift()).cumsum()
    run_length = missing.groupby(run_id).transform("size")

    is_gap = missing & (run_length >= MIN_GAP_MONTHS)
    gap_count = run_id[is_gap].nunique()
    return series[~missing | is_gap], gap_count


def main() -> None:
    df = pd.read_csv(INPUT_PATH)
    # 'YYYY-MM' -> first day of the month, so plotly can use a time axis.
    df["Date"] = pd.to_datetime(df["Date"], format="%Y-%m")

    # One panel per variable, stacked, sharing the time axis: zooming one
    # panel zooms all of them.
    fig = make_subplots(
        rows=len(PANELS), cols=1, shared_xaxes=True, vertical_spacing=0.06,
        subplot_titles=[col for col, *_ in PANELS],
    )

    for row, (col, label, color, marker_size, value_format) in enumerate(PANELS, start=1):
        series, gap_count = with_gaps(df, col)
        fig.add_trace(
            go.Scatter(
                x=series.index, y=series, name=col,
                mode="lines+markers",
                # connectgaps=False: the line breaks at the missing values left in.
                connectgaps=False,
                line=dict(color=color, width=2), marker=dict(size=marker_size),
                hovertemplate=f"{value_format}<extra>{col}</extra>",
            ),
            row=row, col=1,
        )
        fig.update_yaxes(title_text=label, row=row, col=1)
        print(
            f"{col}: {series.notna().sum()} months with data, "
            f"{gap_count} gap(s) of {MIN_GAP_MONTHS}+ months"
        )

    # Time-window controls: buttons above the top panel, slider below the
    # bottom panel. The axes are linked, so both control all panels.
    fig.update_xaxes(
        rangeselector=dict(
            buttons=[
                dict(count=1, label="1y", step="year", stepmode="backward"),
                dict(count=5, label="5y", step="year", stepmode="backward"),
                dict(step="all", label="All"),
            ],
        ),
        row=1, col=1,
    )
    fig.update_xaxes(
        rangeslider=dict(visible=True, thickness=0.05),
        row=len(PANELS), col=1,
    )
    fig.update_xaxes(hoverformat="%b %Y", showspikes=True, spikemode="across")

    fig.update_layout(
        title="Monthly control variables",
        template="plotly_white",
        height=850,
        showlegend=False,
        # Hovering anywhere shows the values of all panels for that month.
        hovermode="x unified",
        margin=dict(t=90, b=60),
    )

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    # Embed plotly.js so the file works without an internet connection.
    fig.write_html(OUTPUT_PATH, include_plotlyjs=True)
    print(f"Saved interactive plot to {OUTPUT_PATH.resolve()}")


if __name__ == "__main__":
    main()
