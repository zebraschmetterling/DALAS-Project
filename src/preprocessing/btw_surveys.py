"""
Generated by Claude

This script turns the raw federal election polls (data/interim/surveys_bund.csv) into a clean
table with one row per survey: | week | institute | <party shares as float> |.
Output in data/processed/btw_surveys.csv

"week" (ISO format YYYY-Www, e.g. 2026-W01) is the ISO week in which the majority of the field period ("Zeitraum") lies
(ties -> later week; falls back to the week of "Datum" if Zeitraum is unusable),

"Sonstige" (label "Other") always contains FW + PIRATEN + everything listed under it
(back-filled as 100 - sum of all other parties when it is missing).

Institute and party labels come from labels.py in this folder.

`-`, `–`, `?` and blank cells become NaN, and fully identical rows are dropped.

Surveys whose `week` falls before 2013 are dropped

Usage:
    python src/data/btw_surveys.py [--input PATH] [--output PATH]
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

# Label tables for institutes and parties (labels.py lives next to this script)
from labels import get_institute_label, get_party_label

# ---------------------------------------------------------------------------
# Paths (resolved relative to this file, so the script works from any cwd)
# ---------------------------------------------------------------------------
SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_INPUT = SCRIPT_DIR / "../../data/interim/surveys_bund.csv"
DEFAULT_OUTPUT = SCRIPT_DIR / "../../data/processed/btw_surveys.csv"

# ---------------------------------------------------------------------------
# Column names as they appear in the raw CSV
# ---------------------------------------------------------------------------
COL_INSTITUTE = "Institut"
COL_DATE = "Datum"
COL_PERIOD = "Zeitraum"
COL_RESPONDENTS = "Befragte"
COL_OTHERS = "Sonstige"
COL_NONVOTERS_PREFIX = "Nichtwähler"  # "Nichtwähler/ Unentschl." is not a party share

# Parties that are not tracked on their own but folded into "Sonstige"
PARTIES_MERGED_INTO_OTHERS = ["FW", "PIRATEN"]

# Values that mean "no result" for a party (all dash variants + unknown)
MISSING_TOKENS = {"", "?", "-", "–", "—", "nan"}

# A field period longer than this is considered implausible -> use Datum instead
MAX_PERIOD_DAYS = 21

# Matches "dd.mm." optionally followed by a 2- or 4-digit year, e.g. "02.10." or "02.10.2026"
PERIOD_DATE_RE = re.compile(r"(\d{1,2})\.(\d{1,2})\.(\d{4}|\d{2})?")

# Matches a number with optional decimal part (decimal sign already normalised to '.')
NUMBER_RE = re.compile(r"\d+(?:\.\d+)?")


# ---------------------------------------------------------------------------
# Helpers: labels
# ---------------------------------------------------------------------------
def institute_label(name: str) -> str | None:
    """Look up the institute label in labels.py, also trying common spelling variants.

    Raw names like "Verian(Emnid)" or "Forsch'gr. Wahlen" (straight apostrophe) are not
    keys in INSTITUTE_TO_LABEL, so the outer name, the bracketed name and the
    typographic apostrophe are tried as well.
    """
    candidates = [name, name.replace("'", "’")]
    bracket = re.match(r"\s*([^()]+?)\s*\(([^()]+)\)\s*$", name)
    if bracket:
        candidates += [bracket.group(1), bracket.group(2)]
    for candidate in candidates:
        label = get_institute_label(candidate)
        if label is not None:
            return label
    return None


def apply_labels(names: pd.Series, lookup, what: str) -> pd.Series:
    """Map raw names to labels; names without a label are kept as-is (with a warning)."""
    labels = {name: lookup(name) for name in names.unique()}
    unmapped = sorted(name for name, label in labels.items() if label is None)
    if unmapped:
        print(f"Warning: no {what} label in labels.py for {unmapped}, keeping the raw names.")
    return names.map(lambda n: labels[n] if labels[n] is not None else n)


# ---------------------------------------------------------------------------
# Helpers: numbers
# ---------------------------------------------------------------------------
def normalise_cell(value: str) -> str:
    """Drop '%', switch decimal ',' to '.', trim whitespace."""
    return str(value).replace("%", "").replace(",", ".").strip()


def parse_party_share(value: str) -> float:
    """Party cell -> float. '-', '–', '?' and blanks become NaN."""
    cleaned = normalise_cell(value)
    if cleaned in MISSING_TOKENS:
        return np.nan
    try:
        return float(cleaned)
    except ValueError:
        print(f"Warning: could not parse party share {value!r}, treating it as missing.")
        return np.nan


def parse_others(value: str) -> float:
    """'Sonstige' cell -> float.

    The cell may list several parties, e.g. "PIR 2 % Sonst. 5 %"; all numbers are summed.
    Blank / '?' / dashes return NaN, so the caller can back-fill it with 100 - sum.
    """
    cleaned = normalise_cell(value)
    if cleaned in MISSING_TOKENS:
        return np.nan
    numbers = NUMBER_RE.findall(cleaned)
    if not numbers:
        return np.nan
    return float(sum(float(n) for n in numbers))


# ---------------------------------------------------------------------------
# Helpers: ISO week
# ---------------------------------------------------------------------------
def _to_year(raw: str | None, default: int) -> int:
    """Expand an optional 2- or 4-digit year string."""
    if not raw:
        return default
    return int(raw) + 2000 if len(raw) == 2 else int(raw)


def parse_period(period: str, published: date) -> tuple[date, date] | None:
    """Parse Zeitraum (e.g. '02.10.–16.10.') into (start, end) dates.

    Zeitraum usually has no year, so it is derived from the publication date (Datum):
    the end lies on/just before Datum, and the start lies before the end
    (handles periods crossing New Year, e.g. '28.12.–05.01.').
    Returns None if Zeitraum is not well specified.
    """
    matches = PERIOD_DATE_RE.findall(str(period))
    if not 1 <= len(matches) <= 2:
        return None
    (d1, m1, y1), (d2, m2, y2) = matches[0], matches[-1]  # single day -> start == end
    try:
        end = date(_to_year(y2, published.year), int(m2), int(d2))
        # Without an explicit year an end date far after publication belongs to last year
        if not y2 and end > published + timedelta(days=30):
            end = end.replace(year=end.year - 1)
        start = date(_to_year(y1, end.year), int(m1), int(d1))
        if not y1 and start > end:
            start = start.replace(year=start.year - 1)
    except ValueError:  # e.g. 31.02.
        return None
    # Plausibility: correct order, reasonable length, not long after publication
    if start > end or (end - start).days > MAX_PERIOD_DAYS or end > published + timedelta(days=7):
        return None
    return start, end


def survey_iso_week(published: date, period: str) -> tuple[int, int, bool]:
    """Return (iso_year, iso_week, used_period).

    With a valid Zeitraum: the ISO week containing the most field days; on a tie the
    later week wins. Otherwise: the ISO week of Datum.
    """
    span = parse_period(period, published)
    if span is None:
        iso = published.isocalendar()
        return iso.year, iso.week, False
    start, end = span
    days_per_week = Counter(
        tuple(d.isocalendar())[:2] for d in pd.date_range(start, end).date
    )
    # max over (day count, (year, week)) -> ties resolved towards the later week
    year, week = max(days_per_week, key=lambda yw: (days_per_week[yw], yw))
    return year, week, True


# ---------------------------------------------------------------------------
# Main processing
# ---------------------------------------------------------------------------
def process(raw: pd.DataFrame) -> pd.DataFrame:
    df = raw.copy()
    df.columns = [c.strip() for c in df.columns]
    df = df.apply(lambda col: col.str.strip())

    # Everything that is not metadata (or non-voters) is a party column
    meta = {COL_INSTITUTE, COL_DATE, COL_PERIOD, COL_RESPONDENTS, COL_OTHERS}
    party_cols = [
        c for c in df.columns if c not in meta and not c.startswith(COL_NONVOTERS_PREFIX)
    ]
    for col in PARTIES_MERGED_INTO_OTHERS:  # make sure FW/PIRATEN exist even if absent
        if col not in df.columns:
            df[col] = ""
            party_cols.append(col)

    # 1. Party shares: drop '%', ',' -> '.', float; '-' / '–' / '?' -> NaN
    for col in party_cols:
        df[col] = df[col].map(parse_party_share).astype(float)

    # 2. Sonstige: sum all listed values; if blank / '?' -> 100 - sum of all other parties
    df[COL_OTHERS] = df[COL_OTHERS].map(parse_others).astype(float)
    party_sum = df[party_cols].sum(axis=1, min_count=1)
    backfill = df[COL_OTHERS].isna() & party_sum.notna()
    df.loc[backfill, COL_OTHERS] = (100 - party_sum[backfill]).clip(lower=0)
    print(f"Back-filled 'Sonstige' as 100 - sum of other parties in {backfill.sum()} rows.")

    # 3. Fold FW and PIRATEN into Sonstige and remove them as separate columns
    df[COL_OTHERS] = df[COL_OTHERS] + df[PARTIES_MERGED_INTO_OTHERS].fillna(0).sum(axis=1)
    party_cols = [c for c in party_cols if c not in PARTIES_MERGED_INTO_OTHERS] + [COL_OTHERS]
    df[party_cols] = df[party_cols].round(2)  # remove float noise like 6.999999

    # 4. Drop fully identical rows (compared after cleaning, so '-' vs '–' does not matter)
    before = len(df)
    df = df.drop_duplicates().reset_index(drop=True)
    print(f"Dropped {before - len(df)} fully identical rows.")

    # 5. Publication date; rows without a valid Datum cannot be assigned to a week
    df["_published"] = pd.to_datetime(df[COL_DATE], format="%d.%m.%Y", errors="coerce")
    invalid = df["_published"].isna()
    if invalid.any():
        print(f"Warning: dropping {invalid.sum()} rows with an invalid 'Datum': "
              f"{df.loc[invalid, COL_DATE].tolist()}")
        df = df[~invalid].reset_index(drop=True)

    # 6. ISO year/week from Zeitraum (majority of field days), fallback Datum
    weeks = [
        survey_iso_week(published.date(), period)
        for published, period in zip(df["_published"], df[COL_PERIOD])
    ]
    # ISO 8601 week notation "YYYY-Www" (e.g. 2026-W01); zero-padding keeps it sortable as text
    df["week"] = [f"{year}-W{week:02d}" for year, week, _ in weeks]
    n_fallback = sum(not w[2] for w in weeks)
    print(f"Week taken from 'Datum' (Zeitraum missing/unclear) for {n_fallback} rows.")

    # 7. Labels for institutes and parties (from labels.py)
    df["institute"] = apply_labels(df[COL_INSTITUTE], institute_label, "institute")
    party_label_map = dict(
        zip(party_cols, apply_labels(pd.Series(party_cols), get_party_label, "party"))
    )
    df = df.rename(columns=party_label_map)

    # 8. Final schema: | week | institute | party shares |
    result = df[["week", "institute", *party_label_map.values()]]
    return result.sort_values(["week", "institute"]).reset_index(drop=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    input_path = args.input.resolve()
    if not input_path.exists():
        sys.exit(f"Error: input file not found: {input_path}")

    # Read everything as text so that '–', '?' and blanks are handled explicitly
    raw = pd.read_csv(input_path, dtype=str, keep_default_na=False)
    print(f"Read {len(raw)} rows from {input_path}")

    result = process(raw)

    output_path = args.output.resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(output_path, index=False)
    print(f"Wrote {len(result)} rows to {output_path}")


if __name__ == "__main__":
    main()
