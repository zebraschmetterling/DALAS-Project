"""
Generated by Claude

Build the monthly control-variable table.

MOST IMPORTANT: The output data/processed/monthly_controls.csv contains exactly
one row per month (Date = YYYY-MM) from the FULL OUTER JOIN of government
satisfaction and the monthly controls. No month from either source is lost,
and missing values are left blank.

Inputs (paths relative to this file):
    1. ../../data/interim/regierungszufriedenheit.csv
       Datum,Monat,sehr zufrieden,zufrieden,weniger zufrieden,gar nicht zufrieden
    2. ../../data/interim/controls_monthly.csv
       Monat,arbeitslosenquote,asylantraege

Output schema:
    Date | Gouvernement Satisfaction | Unemployment rate | Asylum applications

Run with:
    python src/data/monthly_controls.py
"""

from pathlib import Path

import pandas as pd

# Resolve paths relative to this script, so it works from any working directory.
SCRIPT_DIR = Path(__file__).resolve().parent
SATISFACTION_PATH = SCRIPT_DIR / "../../data/interim/regierungszufriedenheit.csv"
CONTROLS_PATH = SCRIPT_DIR / "../../data/interim/controls_monthly.csv"
OUTPUT_PATH = SCRIPT_DIR / "../../data/processed/monthly_controls.csv"


def load_satisfaction() -> pd.DataFrame:
    """Load file 1: one government-satisfaction value per month."""
    df = pd.read_csv(SATISFACTION_PATH)

    # Several surveys can fall into the same month: keep the earliest one.
    before = len(df)
    df = df.sort_values("Datum").drop_duplicates("Monat", keep="first")
    print(f"Removed {before - len(df)} duplicate month(s) from {SATISFACTION_PATH.name}")

    # Satisfaction = 'zufrieden' + 'sehr zufrieden'. min_count=1 keeps the
    # result missing when both parts are missing, instead of turning it into 0.
    df["Gouvernement Satisfaction"] = df[["zufrieden", "sehr zufrieden"]].sum(
        axis=1, min_count=1
    )

    # 'Datum' and the individual answer categories are not needed any more.
    return df[["Monat", "Gouvernement Satisfaction"]]


def load_controls() -> pd.DataFrame:
    """Load file 2: unemployment rate and asylum applications per month."""
    df = pd.read_csv(CONTROLS_PATH)

    # Drop rows where 'Monat' is the only filled column (no actual data).
    before = len(df)
    df = df.dropna(subset=["arbeitslosenquote", "asylantraege"], how="all")
    print(f"Dropped {before - len(df)} row(s) from {CONTROLS_PATH.name} that only contain 'Monat'")

    return df.rename(
        columns={
            "arbeitslosenquote": "Unemployment rate",
            "asylantraege": "Asylum applications",
        }
    )


def main() -> None:
    # Full outer join on the month: keep every month from both sources.
    merged = pd.merge(load_satisfaction(), load_controls(), on="Monat", how="outer")

    # 'Monat' is already ISO 'YYYY-MM', so sorting the text sorts by time.
    merged = merged.rename(columns={"Monat": "Date"}).sort_values("Date")

    # The join turns integer columns with gaps into floats (35 -> 35.0).
    # Nullable integers keep whole numbers while gaps stay missing.
    for col in ["Gouvernement Satisfaction", "Asylum applications"]:
        merged[col] = merged[col].astype("Int64")

    # na_rep="" writes missing values as empty cells, not as 'nan'.
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    merged.to_csv(OUTPUT_PATH, index=False, na_rep="")

    print(f"Wrote {len(merged)} rows to {OUTPUT_PATH.resolve()}")
    print("Missing values per column:")
    for col, count in merged.isna().sum().items():
        print(f"  {col}: {count}")


if __name__ == "__main__":
    main()
